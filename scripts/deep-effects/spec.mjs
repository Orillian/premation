// Program X (docs/PROGRAM_DEEP_EFFECTS.md): the deep effects' controls — the
// one source gen.mjs writes the catalog, the TypeScript defs, the folders and
// the AI enum from. Params: { key, label, type, unit?, min?, max?, precision?,
// options? (labels, menu order = values 0..n), group?, default }. `time: true`
// appends Animate With Time + Time (the layer clock drives `time`).

const pct = (key, label, def, max = 100, min = 0, extra = {}) => ({ key, label, type: 'number', unit: '%', min, max, default: def, ...extra });
const px = (key, label, def, max = 1000, min = 0, extra = {}) => ({ key, label, type: 'number', unit: 'px', min, max, default: def, ...extra });
const deg = (key, label, def, min = -3600, max = 3600, extra = {}) => ({ key, label, type: 'number', unit: '°', min, max, default: def, ...extra });
const num = (key, label, def, min, max, extra = {}) => ({ key, label, type: 'number', min, max, default: def, ...extra });
const col = (key, label, def, extra = {}) => ({ key, label, type: 'color', default: def, ...extra });
const chk = (key, label, def = false, extra = {}) => ({ key, label, type: 'checkbox', default: def, ...extra });
const menu = (key, label, options, def = 0, extra = {}) => ({ key, label, type: 'enum', options, default: def, ...extra });
const layer = (key, label, extra = {}) => ({ key, label, type: 'layer', default: '', ...extra });
const point = (key, label, dx, dy) => [px(`${key}X`, `${label} X`, dx, 100000, -100000), px(`${key}Y`, `${label} Y`, dy, 100000, -100000)];
const seed = () => num('seed', 'Random Seed', 1, 0, 99999, { precision: 0 });
const mask = (key, label, extra = {}) => ({ key, label, type: 'maskPath', default: '', ...extra });
const curve = (key, label, extra = {}) => ({ key, label, type: 'curve', default: [[0, 0], [255, 255]], ...extra });
const real = (key, label, def, min, max, precision = 2, extra = {}) => ({ key, label, type: 'number', min, max, precision, default: def, ...extra });

